SELECT table_name
FROM user_tables
WHERE UPPER(table_name) IN (
    'PRODUCTOS',
    'INVENTARIO',
    'SUCURSALES'
)
ORDER BY table_name;



SELECT table_name, column_name, data_type
FROM user_tab_columns
WHERE UPPER(table_name) IN (
    'PRODUCTOS',
    'INVENTARIO',
    'SUCURSALES'
)
ORDER BY table_name, column_id;




SELECT column_name, data_type
FROM user_tab_columns
WHERE table_name = 'PRODUCTOS'
ORDER BY column_id;



SELECT column_name, data_type
FROM user_tab_columns
WHERE table_name = 'INVENTARIO'
ORDER BY column_id;



SELECT
    argument_name,
    position,
    in_out,
    data_type
FROM user_arguments
WHERE UPPER(object_name) = 'SP_PROCESAR_CHECKOUT_ATOMICO'
ORDER BY sequence;




SELECT line, text
FROM user_source
WHERE UPPER(name) = 'SP_PROCESAR_CHECKOUT_ATOMICO'
  AND type = 'PROCEDURE'
  AND (
      UPPER(text) LIKE '%CLIENTE%'
      OR UPPER(text) LIKE '%ROLLBACK%'
      OR UPPER(text) LIKE '%COMMIT%'
      OR UPPER(text) LIKE '%STOCK_DISPONIBLE%'
      OR UPPER(text) LIKE '%RAISE_APPLICATION_ERROR%'
  )
ORDER BY line;



SELECT COUNT(*) AS EXISTE_CLIENTE
