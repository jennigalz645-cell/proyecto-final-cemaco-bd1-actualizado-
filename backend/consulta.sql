FROM USER_SOURCE
WHERE UPPER(NAME) = 'SP_PROCESAR_CHECKOUT_ATOMICO'
  AND TYPE = 'PROCEDURE'
  AND UPPER(TEXT) LIKE '%FROM CLIENTE%'
ORDER BY LINE;


