
SELECT
    ID_PASARELA,
    NOMBRE,
    PORCENTAJE_COMISION
FROM PASARELAS_PAGO
ORDER BY ID_PASARELA;

SELECT
    ESTADO,
    CANAL_ENTREGA,
    COUNT(*) AS CANTIDAD
FROM ORDENES
GROUP BY ESTADO, CANAL_ENTREGA
ORDER BY ESTADO, CANAL_ENTREGA;

SELECT
    table_name,
    constraint_name,
    constraint_type,
    search_condition
FROM user_constraints
WHERE table_name IN (
    'ORDENES',
    'TRANSACCIONES_PAGO',
    'INVENTARIO'
)
AND constraint_type IN ('C', 'R', 'P', 'U')
ORDER BY table_name, constraint_type, constraint_name;

SELECT
    COUNT(*) AS TOTAL_ORDENES,
    SUM(TOTAL_BRUTO) AS TOTAL_BRUTO
FROM ORDENES;

SELECT
    COUNT(*) AS TOTAL_TRANSACCIONES,
    SUM(MONTO_BRUTO) AS MONTO_BRUTO,
    SUM(COMISION_PASARELA) AS COMISIONES,
    SUM(MONTO_NETO) AS MONTO_NETO
FROM TRANSACCIONES_PAGO;


