    D.ID_PRODUCTO AS CODIGO_PRODUCTO_CARRITO,
    P.ID_PRODUCTO,
    P.SKU,
    D.CANTIDAD
FROM DETALLE_CARRITO D
LEFT JOIN PRODUCTOS P
    ON P.SKU = D.ID_PRODUCTO
    OR TO_CHAR(P.ID_PRODUCTO) = D.ID_PRODUCTO
ORDER BY D.ID_CARRITO;

