SELECT
    CONSTRAINT_NAME,
    STATUS
FROM USER_CONSTRAINTS
WHERE TABLE_NAME = 'DETALLE_CARRITO'
  AND CONSTRAINT_TYPE = 'R';
  
  
  DECLARE
    V_EXISTE NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO V_EXISTE
    FROM CARRITOS_COMPRAS
    WHERE ID_CARRITO = 'CART-TEST-EXP-01';

    IF V_EXISTE > 0 THEN
        RAISE_APPLICATION_ERROR(
            -20010,
            'El carrito de prueba ya existe. No se modificó.'
        );
    END IF;

    INSERT INTO CARRITOS_COMPRAS (
        ID_CARRITO,
        ID_USUARIO,
        ESTADO,
        ULTIMA_ACTUALIZACION,
        ID_SUCURSAL
    )
    VALUES (
        'CART-TEST-EXP-01',
        'USER-TEST-01',
        'PENDIENTE_PAGO',
        SYSTIMESTAMP - INTERVAL '20' MINUTE,
        1
    );

    INSERT INTO DETALLE_CARRITO (
        ID_DETALLE,
        ID_CARRITO,
        ID_PRODUCTO,
        CANTIDAD
    )
    VALUES (
        (SELECT NVL(MAX(ID_DETALLE), 0) + 1 FROM DETALLE_CARRITO),
        'CART-TEST-EXP-01',
        'FER-001',
        1
    );

    UPDATE INVENTARIO
    SET STOCK_DISPONIBLE = STOCK_DISPONIBLE - 1,
        STOCK_RESERVADO = STOCK_RESERVADO + 1
    WHERE ID_SUCURSAL = 1
      AND ID_PRODUCTO = 1
      AND STOCK_DISPONIBLE >= 1;

    IF SQL%ROWCOUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(
            -20011,
            'No fue posible reservar el producto para la prueba.'
        );
    END IF;

    COMMIT;
END;
