CREATE OR REPLACE PROCEDURE SP_EXPIRAR_CARRITOS_INACTIVOS
IS
    V_CARRITOS_EXPIRADOS NUMBER := 0;
    V_ID_PRODUCTO NUMBER;
BEGIN
    FOR R_CARRITO IN (
        SELECT ID_CARRITO, ID_SUCURSAL
        FROM CARRITOS_COMPRAS
        WHERE ESTADO = 'PENDIENTE_PAGO'
          AND ULTIMA_ACTUALIZACION <
              SYSTIMESTAMP - INTERVAL '15' MINUTE
        FOR UPDATE
    )
    LOOP
        IF R_CARRITO.ID_SUCURSAL IS NULL THEN
            RAISE_APPLICATION_ERROR(
                -20001,
                'El carrito ' || R_CARRITO.ID_CARRITO ||
                ' no tiene una sucursal asignada.'
            );
        END IF;

        FOR R_DET IN (
            SELECT
                D.ID_PRODUCTO,
                SUM(D.CANTIDAD) AS CANTIDAD
            FROM DETALLE_CARRITO D
            WHERE D.ID_CARRITO = R_CARRITO.ID_CARRITO
            GROUP BY D.ID_PRODUCTO
        )
        LOOP
            BEGIN
                SELECT ID_PRODUCTO
                INTO V_ID_PRODUCTO
                FROM PRODUCTOS
                WHERE SKU = R_DET.ID_PRODUCTO
                   OR TO_CHAR(ID_PRODUCTO) = R_DET.ID_PRODUCTO
                FETCH FIRST 1 ROW ONLY;
            EXCEPTION
                WHEN NO_DATA_FOUND THEN
                    RAISE_APPLICATION_ERROR(
                        -20002,
                        'No se pudo relacionar el producto ' ||
                        R_DET.ID_PRODUCTO || ' del carrito ' ||
                        R_CARRITO.ID_CARRITO
                    );
            END;

            UPDATE INVENTARIO
            SET STOCK_DISPONIBLE =
                    STOCK_DISPONIBLE + R_DET.CANTIDAD,
                STOCK_RESERVADO =
                    STOCK_RESERVADO - R_DET.CANTIDAD
            WHERE ID_SUCURSAL = R_CARRITO.ID_SUCURSAL
              AND ID_PRODUCTO = V_ID_PRODUCTO
              AND STOCK_RESERVADO >= R_DET.CANTIDAD;

            IF SQL%ROWCOUNT = 0 THEN
                RAISE_APPLICATION_ERROR(
                    -20003,
                    'No existe reserva suficiente para el producto ' ||
                    R_DET.ID_PRODUCTO || ' en la sucursal ' ||
                    R_CARRITO.ID_SUCURSAL
                );
            END IF;
        END LOOP;

        UPDATE CARRITOS_COMPRAS
        SET ESTADO = 'EXPIRADO',
            ULTIMA_ACTUALIZACION = SYSTIMESTAMP
        WHERE ID_CARRITO = R_CARRITO.ID_CARRITO
          AND ESTADO = 'PENDIENTE_PAGO';

        IF SQL%ROWCOUNT = 1 THEN
            INSERT INTO BITACORA_AUDITORIA (DESCRIPCION)
            VALUES (
                'El carrito ' || R_CARRITO.ID_CARRITO ||
                ' expiró y se liberaron sus reservas.'
            );

            INSERT INTO NOTIFICACIONES_VENTAS (MENSAJE)
            VALUES (
                '[VENTAS] Carrito ' || R_CARRITO.ID_CARRITO ||
                ' expirado por superar los 15 minutos sin pago confirmado.'
            );

            V_CARRITOS_EXPIRADOS := V_CARRITOS_EXPIRADOS + 1;
        END IF;
    END LOOP;

    COMMIT;

    DBMS_OUTPUT.PUT_LINE(
        'Proceso completado. Carritos expirados: ' ||
        V_CARRITOS_EXPIRADOS
    );

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END SP_EXPIRAR_CARRITOS_INACTIVOS;
/

