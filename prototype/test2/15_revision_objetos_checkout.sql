
SELECT
    TABLE_NAME,
    COLUMN_NAME,
    DATA_TYPE,
    NULLABLE
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME IN (
    'CLIENTE',
    'ORDENES',
    'PRODUCTOS',
    'INVENTARIO',
    'TRANSACCIONES_PAGO',
    'DETALLE_PEDIDO',
    'DETALLE_PEDIDOS',
    'CARRITOS_COMPRAS',
    'DETALLE_CARRITO',
    'CUPON'
)
ORDER BY TABLE_NAME, COLUMN_ID;

SELECT
    OBJECT_NAME,
    OBJECT_TYPE,
    STATUS
FROM USER_OBJECTS
WHERE OBJECT_TYPE IN (
    'PROCEDURE',
    'FUNCTION',
    'PACKAGE',
    'TRIGGER',
    'VIEW'
)
AND (
    OBJECT_NAME LIKE '%RESERV%'
    OR OBJECT_NAME LIKE '%EXPIR%'
    OR OBJECT_NAME LIKE '%PUNTO%'
    OR OBJECT_NAME LIKE '%CHECKOUT%'
    OR OBJECT_NAME LIKE '%ORDEN%'
    OR OBJECT_NAME LIKE '%CARRITO%'
)
ORDER BY OBJECT_TYPE, OBJECT_NAME;

SELECT
    a.TABLE_NAME,
    a.CONSTRAINT_NAME,
    a.CONSTRAINT_TYPE,
    a.R_CONSTRAINT_NAME
FROM USER_CONSTRAINTS a
WHERE a.TABLE_NAME IN (
    'ORDENES',
    'CLIENTE',
    'DETALLE_PEDIDO',
    'DETALLE_PEDIDOS'
)
AND a.CONSTRAINT_TYPE IN ('P', 'R', 'U')
ORDER BY a.TABLE_NAME, a.CONSTRAINT_TYPE;


