SET SERVEROUTPUT ON;

DECLARE
    V_STOCK_ANTES NUMBER;
    V_STOCK_DESPUES NUMBER;
    V_ORDENES_ANTES NUMBER;
    V_ORDENES_DESPUES NUMBER;
    V_PAGOS_ANTES NUMBER;
    V_PAGOS_DESPUES NUMBER;
BEGIN
    SELECT STOCK_DISPONIBLE
    INTO V_STOCK_ANTES
    FROM INVENTARIO
    WHERE ID_SUCURSAL = 1
      AND ID_PRODUCTO = 1;

    SELECT COUNT(*) INTO V_ORDENES_ANTES FROM ORDENES;
    SELECT COUNT(*) INTO V_PAGOS_ANTES FROM TRANSACCIONES_PAGO;

    BEGIN
        SP_PROCESAR_CHECKOUT_ATOMICO(
            p_id_cliente => -999999,
            p_id_sucursal => 1,
            p_id_producto => 1,
            p_cantidad => 1,
            p_canal => 'ONLINE',
            p_id_pasarela => 1
        );

        DBMS_OUTPUT.PUT_LINE('ERROR: se acepto un cliente inexistente.');

    EXCEPTION
        WHEN OTHERS THEN
            DBMS_OUTPUT.PUT_LINE('Error esperado: ' || SQLERRM);
    END;

    SELECT STOCK_DISPONIBLE
    INTO V_STOCK_DESPUES
    FROM INVENTARIO
    WHERE ID_SUCURSAL = 1
      AND ID_PRODUCTO = 1;

    SELECT COUNT(*) INTO V_ORDENES_DESPUES FROM ORDENES;
    SELECT COUNT(*) INTO V_PAGOS_DESPUES FROM TRANSACCIONES_PAGO;

    IF V_STOCK_ANTES = V_STOCK_DESPUES
       AND V_ORDENES_ANTES = V_ORDENES_DESPUES
       AND V_PAGOS_ANTES = V_PAGOS_DESPUES THEN
        DBMS_OUTPUT.PUT_LINE('PRUEBA SUPERADA: sin cambios parciales.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('PRUEBA FALLIDA: revisar los cambios.');
    END IF;
END;
/


SELECT COLUMN_NAME, DATA_TYPE, DATA_LENGTH
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME IN ('CLIENTE', 'ORDENES')
  AND COLUMN_NAME = 'ID_CLIENTE';

SELECT COUNT(*) AS ORDENES_SIN_CLIENTE_VALIDO
FROM ORDENES O
WHERE NOT EXISTS (
    SELECT 1
    FROM CLIENTE C
    WHERE C.ID_CLIENTE = O.ID_CLIENTE
);
