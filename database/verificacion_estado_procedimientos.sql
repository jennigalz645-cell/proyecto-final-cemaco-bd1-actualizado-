SELECT o.id_orden, o.id_cliente, o.id_sucursal,
       o.estado, t.id_transaccion, t.monto_bruto
FROM ordenes o
LEFT JOIN transacciones_pago t
    ON t.id_orden = o.id_orden
WHERE o.id_cliente = -999999
ORDER BY o.id_orden;



