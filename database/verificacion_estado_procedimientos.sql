SELECT
    a.TABLE_NAME,
    a.CONSTRAINT_NAME,
    a.COLUMN_NAME,
    c_pk.TABLE_NAME AS TABLA_REFERENCIADA,
    b_pk.COLUMN_NAME AS COLUMNA_REFERENCIADA
FROM USER_CONS_COLUMNS a
JOIN USER_CONSTRAINTS c
    ON a.CONSTRAINT_NAME = c.CONSTRAINT_NAME
JOIN USER_CONS_COLUMNS b_pk
    ON c.R_CONSTRAINT_NAME = b_pk.CONSTRAINT_NAME
JOIN USER_CONSTRAINTS c_pk
    ON c.R_CONSTRAINT_NAME = c_pk.CONSTRAINT_NAME
WHERE c.CONSTRAINT_TYPE = 'R'
  AND a.TABLE_NAME IN ('DETALLE_PEDIDO', 'DETALLE_PEDIDOS')
ORDER BY a.TABLE_NAME;


